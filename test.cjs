const assert=require('node:assert/strict');
const {settings,profile,scheduledTheme,tuningCss}=require('./core');
const {themes}=require('./registry.json');
assert.equal(themes.length,15);
assert.equal(new Set(themes.map(t=>t.id)).size,15);
assert.equal(profile({clarity:999}).clarity,100);
const s=settings({selected:'tl-xin',automatic:{mode:'clock',day:'tl-xin',night:'legacy-cantarella',dayStart:7,nightStart:19}},themes);
const at=(h,m=0)=>new Date(2026,9,9,h,m);
assert.equal(scheduledTheme(s,false,at(6,59)),'legacy-cantarella');
assert.equal(scheduledTheme(s,false,at(7)),'tl-xin');
assert.equal(scheduledTheme(s,false,at(19)),'legacy-cantarella');
s.automatic.dayStart=20;s.automatic.nightStart=6;
assert.equal(scheduledTheme(s,false,at(0)),'tl-xin');
assert.equal(scheduledTheme(s,false,at(6)),'legacy-cantarella');
s.automatic.mode='appearance';
assert.equal(scheduledTheme(s,true),'legacy-cantarella');
s.automatic.mode='off';assert.equal(scheduledTheme(s,true),'tl-xin');
for(const t of themes)assert.ok(tuningCss(t,profile()).includes('@media print'));
console.log('PASS: registry, bounds, day/night switching, midnight and theme CSS.');
